    /**
     * @test
     */
     public function assignUser(): void
     {
         $process = Processes::first();
         self::assertNotNull($process);
         $manager = $this->getManager();


        $response = $this->actingAs($this->getAdmin())->post('/admin/process/assignUser',
            ['process_id' => $process->id, 'assign_user' => $manager->id,
             '_token' => csrf_token()]);

        $response->assertStatus(200);
        $manager->refresh();
        $process->refresh();
        $streams = $process->streams->pluck('id')->toArray();
        $this->assertTrue(in_array($manager->process, $streams));
    }

    /**
     * @test
     */
    public function deployWait()
    {
        $manager = $this->getManager();
        \Auth::setUser($manager);
        /** @var ManticoreService $manticoreService */
        $manticoreService = app(ManticoreService::class);
        for ($i = 1; $i <= 20; $i++) {
            $manticoreService->setStream($manager->process);
            $error = $manticoreService->getError();
            if($error === ''){
                break;
            }

            echo $error."\n";
            sleep(5);
        }

        self::assertSame($error, '');
    }

    /**
     * @test
     */
    public function addRules()
    {
        $manager = $this->getManager();
        \Auth::setUser($manager);
        /** @var ManticoreService $manticoreService */
        $manticoreService = app(ManticoreService::class);
        $manticoreService->setStream($manager->process);
        $manticoreService->truncateRules();

        $rules = ['经', '小', '集', '喜', '@url http://www.xiaomi.com',
                  '@url http://blog.sina.com.cn/liyunjie999',
                  '@url http://blog.sina.com.cn/cosmopolitan2008'];

        foreach ($rules as $rule){
            $response = $this->actingAs($manager)->post('/manager/addRule', ['rule_text' => $rule, '_token' => csrf_token()]);
            $response->assertStatus(200);
        }
    }
