    /**
     * @test
     */
    public function createSource(): void
    {
        $data = [
            'name'  => "source",
            'host'  => 'my-kafka-controller-0.my-kafka-controller-headless.kafka.svc.cluster.local:9092',
            'topic' => 'my-docs',
            'group' => 'ms_test_stream',
            '_token' => csrf_token()
        ];

        $response = $this->actingAs($this->getAdmin())->post("/admin/source/add", $data);
        $response->assertStatus(200);

        $newGoals = Source::where(['name' => $data['name']])->first();

        $this->assertSame([$newGoals->name, $newGoals->host, $newGoals->topic, $newGoals->group],
            [$data['name'], $data['host'], $data['topic'], $data['group']]);

        $response->assertExactJson([
            "success" => "Record is successfully added",
            "id"      => $newGoals->id,
        ]);
    }


