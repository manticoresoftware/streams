func policyJSLT(t *testing.T, expression string) func(string) (string, error) {
	t.Helper()
	if os.Getenv("STREAMS_JSLT_BUNDLE") == "" {
		t.Skip("requires pinned STREAMS_JSLT_BUNDLE")
	}
	fn, err := newJSLT(expression)
	if err != nil {
		t.Fatal(err)
	}
	return fn
}

func policyProcessor(rows []map[string]any, out *[]string) batchProcessor {
	return batchProcessor{
		config: config{output: "0010", maxMessage: 1 << 20}, metrics: &observedBatch{},
		mapDoc: func(raw string) (any, string, error) { return json.RawMessage(raw), raw, nil },
		query: func(_ context.Context, sql string) ([]map[string]any, error) {
			if !strings.HasPrefix(sql, "CALL PQ") {
				return nil, fmt.Errorf("unexpected SQL: %s", sql)
			}
			return rows, nil
		},
		publish: func(_ context.Context, docs []string) error { *out = append(*out, docs...); return nil },
	}
}
func policyRow(documents string) map[string]any {
	return map[string]any{"id": "9007199254740993", "documents": documents, "query": "synthetic", "filters": "f>0", "tags": "{}"}
}

func TestJSLTBatchPolicyNoMatchNeverTransforms(t *testing.T) {
	var output []string
	p := policyProcessor(nil, &output)
	calls := 0
	p.jslt = func(string) (string, error) { calls++; return "", fmt.Errorf("must not run") }
	if err := p.process(context.Background(), []string{`{"id":"unmatched"}`}); err != nil {
		t.Fatal(err)
	}
	if calls != 0 || len(output) != 0 {
		t.Fatalf("calls=%d output=%v", calls, output)
	}
}

func TestJSLTBatchPolicyMetadataAndHighlightOrder(t *testing.T) {
	for _, n := range []int{1, 2, 5} {
		t.Run(strconv.Itoa(n), func(t *testing.T) {
			var rows []map[string]any
			for i := 0; i < n; i++ {
				// PQ returns document 2 first; emission must still follow source order.
				row := policyRow("2,1")
				row["id"] = strconv.FormatInt(9007199254740993+int64(i), 10)
				row["query"] = fmt.Sprintf("query-%d", i)
				if i%2 == 0 {
					row["tags"] = fmt.Sprintf(`{"highlighting":true,"tag":{"ordinal":%d},"externalquery":{"original":"external-%d"}}`, i, i)
				} else {
					row["tags"] = `{"tag":["synthetic",2]}`
				}
				rows = append(rows, row)
			}
			var output, inputs []string
			p := policyProcessor(rows, &output)
			p.config.output = "0011"
			native := policyJSLT(t, `{"id":.id,"kind":.kind,"matching_queries":.matching_queries}`)
			p.jslt = func(s string) (string, error) { inputs = append(inputs, s); return native(s) }
			calls := 0
			p.query = func(_ context.Context, sql string) ([]map[string]any, error) {
				if strings.HasPrefix(sql, "CALL PQ") {
					if !strings.Contains(sql, `source-one`) || strings.Contains(sql, `SOURCE-ONE`) {
						t.Fatalf("PQ should see mapped lowercase input: %s", sql)
					}
					return rows, nil
				}
				if !strings.HasPrefix(sql, "CALL SNIPPETS") || !strings.Contains(sql, `SOURCE-ONE`) {
					t.Fatalf("SNIPPETS must see original input: %s", sql)
				}
				ordinal := calls * 2
				calls++
				return []map[string]any{{"snippet": fmt.Sprintf(`{"id":"two-%d","kind":"highlight"}`, ordinal)}, {"snippet": fmt.Sprintf(`{"id":"one-%d","kind":"highlight"}`, ordinal)}}, nil
			}
			if err := p.process(context.Background(), []string{`{"id":"SOURCE-ONE","kind":"regular"}`, `{"id":"SOURCE-TWO","kind":"regular"}`}); err != nil {
				t.Fatal(err)
			}
			h := (n + 1) / 2
			if calls != h || len(output) != 2*(h+1) || len(inputs) != len(output) {
				t.Fatalf("snippet calls=%d inputs=%d outputs=%d", calls, len(inputs), len(output))
			}
			// Optional private release-worker evidence, generated by PolicyProbe.
			// Compare complete outputs without reimplementing Java metadata assembly.
			if path := os.Getenv("STREAMS_JAVA_POLICY_LOG"); path != "" {
				data, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				found := false
				for _, line := range strings.Split(string(data), "\n") {
					var report struct {
						Case    string   `json:"case"`
						Outputs []string `json:"outputs"`
					}
					if json.Unmarshal([]byte(line), &report) != nil || report.Case != fmt.Sprintf("metadata-%d", n) {
						continue
					}
					found = true
					if len(report.Outputs) != len(output) {
						t.Fatal("actual Java output count differs")
					}
					for i := range output {
						if !sameFixtureJSON(output[i], report.Outputs[i]) {
							t.Fatalf("actual Java differs at output %d: Go=%s Java=%s", i, output[i], report.Outputs[i])
						}
					}
				}
				if !found {
					t.Fatal("actual Java metadata case missing from policy log")
				}
				t.Log("complete outputs equal actual release ManticoreBatch + JsltTransformer + Producer")
			}
			for doc := 0; doc < 2; doc++ {
				for j := 0; j < h; j++ {
					prefix := []string{"one", "two"}[doc]
					want := fmt.Sprintf(`{"id":"%s-%d","kind":"highlight"}`, prefix, j*2)
					if !sameFixtureJSON(output[doc*(h+1)+j], want) {
						t.Fatalf("highlight order: %s want %s", output[doc*(h+1)+j], want)
					}
					if strings.Contains(inputs[doc*(h+1)+j], "matching_queries") {
						t.Fatal("metadata must not be injected into highlighted output")
					}
				}
				regular := output[doc*(h+1)+h]
				var obj struct {
					ID      string                       `json:"id"`
					Matches []map[string]json.RawMessage `json:"matching_queries"`
				}
				if err := json.Unmarshal([]byte(regular), &obj); err != nil {
					t.Fatal(err)
				}
				if obj.ID != []string{"SOURCE-ONE", "SOURCE-TWO"}[doc] || len(obj.Matches) != n {
					t.Fatalf("regular: %s", regular)
				}
				for i, m := range obj.Matches {
					if string(m["queryid"]) != strconv.FormatInt(9007199254740993+int64(i), 10) {
						t.Fatalf("ID precision/order: %s", regular)
					}
					if i%2 == 0 {
						want := fmt.Sprintf(`{"original":"external-%d"}`, i)
						if !sameFixtureJSON(string(m["query"]), want) || m["filters"] != nil || !sameFixtureJSON(string(m["tag"]), fmt.Sprintf(`{"ordinal":%d}`, i)) {
							t.Fatalf("external metadata: %s", regular)
						}
					} else if string(m["query"]) != fmt.Sprintf(`"query-%d"`, i) || string(m["filters"]) != `"f>0"` || string(m["tag"]) != `["synthetic",2]` {
						t.Fatalf("internal metadata: %s", regular)
					}
				}
			}
		})
	}
}

func TestJSLTBatchPolicyPartialFlushErrorDoesNotCommit(t *testing.T) {
	var records []*kgo.Record
	var docs []string
	for i := 0; i < 140; i++ {
		docs = append(docs, strconv.Itoa(i+1))
		records = append(records, &kgo.Record{Topic: "synthetic", Offset: int64(i), Value: []byte(fmt.Sprintf(`{"id":%d}`, i))})
	}
	var output []string
	p := policyProcessor([]map[string]any{policyRow(strings.Join(docs, ","))}, &output)
	native := policyJSLT(t, `if (.id == 130) error("synthetic later failure") else .`)
	calls := 0
	p.jslt = func(s string) (string, error) { calls++; return native(s) }
	var flushSizes []int
	p.publish = func(_ context.Context, values []string) error {
		flushSizes = append(flushSizes, len(values))
		output = append(output, values...)
		return nil
	}
	commits := 0
	err := deliverBatch(context.Background(), p.config, records, p.process, func(context.Context, ...*kgo.Record) error { commits++; return nil })
	if err == nil || !strings.Contains(err.Error(), "transform output with JSLT") || calls != 131 || commits != 0 || !reflect.DeepEqual(flushSizes, []int{128}) || len(output) != 128 {
		t.Fatalf("err=%v calls=%d commits=%d flushes=%v outputs=%d", err, calls, commits, flushSizes, len(output))
	}
	for i, s := range output {
		if s != fmt.Sprintf(`{"id":%d}`, i) {
			t.Fatalf("delivery order at %d: %s", i, s)
		}
	}
	if p.metrics.(*observedBatch).docs != 0 {
		t.Fatal("failed batch unexpectedly reported complete metrics")
	}
	// A real worker returns the error without committing offsets. The 128 confirmed
	// outputs can therefore be duplicated on replay; outputs 128 and 129 were only
	// buffered and are discarded when output 130 fails.
}

func TestJSLTBatchPolicyOutputSizeBoundary(t *testing.T) {
	for _, skip := range []bool{false, true} {
		for _, limit := range []int{5, 6, 7} {
			t.Run(fmt.Sprintf("skip=%v/limit=%d", skip, limit), func(t *testing.T) {
				var output []string
				p := policyProcessor([]map[string]any{policyRow("1")}, &output)
				p.config.maxMessage = limit
				p.config.skipExceeded = skip
				p.jslt = policyJSLT(t, `.payload`)
				// JSON string quotes (2 bytes) plus two UTF-8 e-acute characters (4 bytes).
				err := p.process(context.Background(), []string{`{"payload":"éé"}`})
				rejected := 6 >= limit
				if (err != nil) != (rejected && !skip) {
					t.Fatalf("size=6 limit=%d skip=%v err=%v", limit, skip, err)
				}
				if (!rejected && !reflect.DeepEqual(output, []string{`"éé"`})) || (rejected && len(output) != 0) {
					t.Fatalf("output=%v", output)
				}
			})
		}
	}
}

func TestJSLTBatchPolicyInputSizeAndOffsets(t *testing.T) {
	for _, skip := range []bool{false, true} {
		for _, size := range []int{5, 6, 7} {
			t.Run(fmt.Sprintf("skip=%v/size=%d", skip, size), func(t *testing.T) {
				record := &kgo.Record{Topic: "synthetic", Partition: 2, Offset: 41, Value: []byte(strings.Repeat("x", size))}
				processed, committed := false, false
				err := deliverBatch(context.Background(), config{maxMessage: 6, skipExceeded: skip}, []*kgo.Record{record}, func(_ context.Context, docs []string) error {
					processed = true
					want := []string{string(record.Value)}
					if size >= 6 {
						want = []string{}
					}
					if !reflect.DeepEqual(docs, want) {
						t.Fatalf("process got %v want %v", docs, want)
					}
					return nil
				}, func(_ context.Context, got ...*kgo.Record) error {
					committed = true
					if len(got) != 1 || got[0] != record {
						t.Fatal("must commit original records, including skipped input")
					}
					return nil
				})
				fail := size >= 6 && !skip
				if (err != nil) != fail || processed == fail || committed == fail {
					t.Fatalf("err=%v process=%v commit=%v", err, processed, committed)
				}
			})
		}
	}
}

func TestJSLTBatchPolicyInvalidAndNullSnippets(t *testing.T) {
	for _, tc := range []struct {
		name      string
		snippets  []map[string]any
		queryErr  bool
		wantError bool
		want      []string
	}{
		{name: "plain-text", snippets: []map[string]any{{"snippet": "plain-text"}}, wantError: true},
		{name: "missing-field", snippets: []map[string]any{{}}, wantError: true},
		{name: "nil-field", snippets: []map[string]any{{"snippet": nil}}, wantError: true},
		{name: "JSON-null", snippets: []map[string]any{{"snippet": "null"}}, want: []string{"null", `{"id":1}`}},
		{name: "no-snippet-row", want: []string{`{"id":1}`}},
		{name: "snippet-query-error", queryErr: true, want: []string{`{"id":1}`}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var output []string
			row := policyRow("1")
			row["tags"] = `{"highlighting":true}`
			p := policyProcessor([]map[string]any{row}, &output)
			p.jslt = policyJSLT(t, `.`)
			p.query = func(_ context.Context, sql string) ([]map[string]any, error) {
				if strings.HasPrefix(sql, "CALL PQ") {
					return []map[string]any{row}, nil
				}
				if tc.queryErr {
					return nil, fmt.Errorf("synthetic snippets unavailable")
				}
				return tc.snippets, nil
			}
			err := p.process(context.Background(), []string{`{"id":1}`})
			if (err != nil) != tc.wantError || !reflect.DeepEqual(output, tc.want) {
				t.Fatalf("err=%v output=%v want=%v", err, output, tc.want)
			}
		})
	}
	for _, tc := range []struct {
		name, expression string
		wantError        bool
		want             string
	}{
		{"missing-path", `.absent.path`, false, "null"},
		{"explicit-null", `null`, false, "null"},
		{"error-expression", `error("synthetic")`, true, ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var out []string
			p := policyProcessor([]map[string]any{policyRow("1")}, &out)
			p.jslt = policyJSLT(t, tc.expression)
			err := p.process(context.Background(), []string{`{"id":1}`})
			if (err != nil) != tc.wantError || (!tc.wantError && !reflect.DeepEqual(out, []string{tc.want})) || (tc.wantError && len(out) != 0) {
				t.Fatalf("err=%v output=%v", err, out)
			}
		})
	}
}
